// Builds labready/supabase-quiz-keys.sql from labready/content/quizzes.js so the
// database can mark quiz-link submissions itself. Re-run after editing any quiz:
//   node labready/tools/build-quiz-keys.mjs
// then run the generated SQL in the Supabase SQL editor.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = fileURLToPath(new URL('..', import.meta.url));
const ctx = { window: {} };
vm.runInNewContext(readFileSync(root + 'content/quizzes.js', 'utf8'), ctx);
const bank = ctx.window.LABREADY_QUIZZES;

const rows = [];
let count = 0;
for (const mod of Object.keys(bank.modules).sort()) {
    if (!/^\d{2}$/.test(mod)) throw new Error('Bad module id ' + mod);
    rows.push(bank.modules[mod].questions.map((q, i) => {
        if (!Number.isInteger(q.a) || q.a < 0 || q.a >= q.o.length) throw new Error(`Bad answer for ${mod} Q${i + 1}`);
        count++;
        return `('${mod}',${i},${q.a})`;
    }).join(','));
}
if (!Number.isInteger(bank.passMark) || bank.passMark < 1 || bank.passMark > 100) throw new Error('Bad pass mark');

const sql = `-- GENERATED by labready/tools/build-quiz-keys.mjs from content/quizzes.js. Do not edit by hand.
-- Answer keys for quiz links. Stored in the private schema, which the API can't read.
-- Run after supabase-app-schema.sql, and again whenever a quiz changes.

begin;
delete from private.quiz_keys;
insert into private.quiz_keys (module_id, q, answer) values
${rows.join(',\n')};
create or replace function private.quiz_pass_mark()
returns int language sql immutable set search_path = '' as $$ select ${bank.passMark} $$;
commit;
`;
writeFileSync(root + 'supabase-quiz-keys.sql', sql);
console.log(`Wrote ${count} answers across ${Object.keys(bank.modules).length} modules, pass mark ${bank.passMark}%.`);
